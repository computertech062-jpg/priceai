const DICTS = { ku, ar, en };
// زمانەکانی ڕاست-بۆ-چەپ
const RTL = new Set(["ku", "ar"]);
const HTML_LANG = { ku: "ckb", ar: "ar", en: "en" };
let current = "ku";

export const lang = () => current;
export const dicts = DICTS;

export function t(key, vars) {
  let s = DICTS[current][key] ?? DICTS.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
  return s;
}

export const isRtl = (l = current) => RTL.has(l);

export function applyLang(l) {
  current = DICTS[l] ? l : "ku";
  const html = document.documentElement;
  html.lang = HTML_LANG[current];
  html.dir = isRtl() ? "rtl" : "ltr";
  document.body?.setAttribute("lang", HTML_LANG[current]);
}
